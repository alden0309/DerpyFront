/** What it takes before anyone will have you at a trade (or you can set up in it). */
export interface JobRequires {
  skills?: Partial<Record<import("./Types").Skill, number>>;
  /** A name in the underworld. */
  notoriety?: number;
  /** Only in a port town; only in the north (whaling grounds). */
  coastal?: boolean;
  north?: boolean;
  /**
   * People who'll vouch for you: the underworld (a den you know, a name, or
   * a crooked upbringing), the native peoples (born to them, or woods-wise
   * and travelled among them), or the sea (seamanship, or a sea upbringing).
   */
  contacts?: "underworld" | "natives" | "sea";
  /** Pirate waters in pirate years (or a name that draws the crews). */
  pirates?: boolean;
}

