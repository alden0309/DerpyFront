/** The group a background is listed under in the register. */
export function backgroundGroup(
  b: BackgroundId,
  bg: BackgroundDef,
  jobs: Record<JobKind, JobDef>,
): JobGroup {
  if (bg.native) return "native";
  if (b === "gentry") return "learned";
  return bg.job ? jobGroupOf(bg.job, jobs[bg.job]) : "learned";
}
